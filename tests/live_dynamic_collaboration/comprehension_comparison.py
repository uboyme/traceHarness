"""Paired single-vs-multi comparison on one read-heavy comprehension task.

The task is "understand this codebase and write the answer down" over a corpus
that no single context window can hold. Unlike the writable comparison there are
no child Patches to read and integrate, so the main agent's cost is synthesis
only - which is the arm of the trade-off record 074 could not separate.

This uses the repository's own `execution_strategy` comparison: two arms of the
same benchmark, baseline `single` and candidate `multi`, run by `traceh eval`
with one run plan. Nothing here scores anything; the original comparison owner
decides the verdict from the two reports.
"""

