def validate(output: Path) -> dict:
    data = read_input(output, "contract.json").data
    if (output / "comparison_driver.py").read_bytes() != Path(__file__).read_bytes():
        raise ValueError("comprehension-driver-drift")
    for relative, digest in data["files"].items():
        if digest_bytes((output / relative).read_bytes()) != digest:
            raise ValueError("comprehension-material-drift")
    return data


def preflight(output: Path) -> None:
    validate(output)
    sandbox = load_sandbox_file(output / "sandbox.json")
    if sandbox.policy.network != "none" or sandbox.plugin_grants:
        raise ValueError("comprehension-sandbox-policy-unexpected")
    case = read_input(output / "material", "dataset.json").data["cases"][0]
    paths = corpus_paths_from(output)
    reference = _reference(output / "material/initial", paths)
    outcomes = []
    # "invented" is the rule that carries the weight: a deliverable that meets
    # every count but cites one path that is not in the tree must still fail.
    for shape in ("absent", "reference", "invented"):
        with TemporaryDirectory(prefix="traceh-comprehension-") as directory:
            work = Path(directory).resolve()
            shutil.copytree(output / "material/initial", work, dirs_exist_ok=True)
            repaired = shape == "reference"
            if shape == "reference":
                (work / DELIVERABLE).write_text(reference, encoding="utf-8")
            elif shape == "invented":
                (work / DELIVERABLE).write_text(
                    reference + "\nSee also `src/traceh/does_not_exist/router.py`.\n",
                    encoding="utf-8",
                )
            result = subprocess.run(
                [
                    "docker",
                    "--context",
                    sandbox.policy.docker_context,
                    "run",
                    "--rm",
                    "--pull",
                    "never",
                    "--network",
                    "none",
                    "--memory",
                    "256m",
                    "--pids-limit",
                    "64",
                    "--cpus",
                    "1",
                    "--mount",
                    f"type=bind,source={work},target=/work,readonly",
                    "--workdir",
                    "/work",
                    sandbox.policy.image,
                    *case["verification"]["commands"][0]["argv"],
                ],
                capture_output=True,
                text=True,
                encoding="utf-8",
                timeout=180,
            )
            expected = 0 if repaired else 1
            if result.returncode != expected or (
                not repaired and "AssertionError" not in result.stderr
            ):
                raise ValueError(
                    f"comprehension-preflight-failed:{shape}:{result.returncode}:"
                    f"{result.stderr[-400:]}"
                )
            if shape == "invented" and "citations that do not resolve" not in result.stderr:
                raise ValueError("comprehension-preflight-invented-wrong-reason")
            outcomes.append(
                {
                    "shape": shape,
                    "exit_code": result.returncode,
                    "stdout": result.stdout.strip()[-200:],
                    "reason": result.stderr.strip().splitlines()[-1][-160:]
                    if result.returncode
                    else "",
                }
            )
    write(
        output / "preflight.json",
        {
            "contract_digest": digest_bytes((output / "contract.json").read_bytes()),
            "outcomes": outcomes,
        },
    )


def corpus_paths_from(output: Path) -> tuple[str, ...]:
    """The frozen corpus as materialized, read back from the initial tree."""
    initial = output / "material/initial"
    return tuple(
        sorted(
            p.relative_to(initial).as_posix()
            for p in initial.rglob("*")
            if p.is_file() and not {".git", "__pycache__"} & set(p.parts)
        )
    )


async def run(output: Path, env_file: Path) -> int:
    from traceh.cli.main import _configure_from_environment, _eval, build_parser

    validate(output)
    preflight_data = read_input(output, "preflight.json").data
    if preflight_data["contract_digest"] != digest_bytes((output / "contract.json").read_bytes()):
        raise ValueError("comprehension-preflight-drift")
    with (output / "started.json").open("x", encoding="utf-8") as stream:
        stream.write('{"started":true}\n')
    args = build_parser().parse_args(
        [
            "eval",
            str(output / "material"),
            "--run-plan",
            str(output / "material/run-plan.json"),
            "--output",
            str(output / "experiment"),
            "--env-file",
            str(env_file),
        ]
    )
    _configure_from_environment(args)
    code = await _eval(args)
    write(output / "execution.json", {"exit_code": code})
    print(json.dumps({"exit_code": code}))
    return code


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("prepare", "preflight", "run"))
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--repository", type=Path)
    parser.add_argument("--sandbox", type=Path)
    parser.add_argument("--env-file", type=Path, default=Path(".env"))
    args = parser.parse_args()
    target = args.output.resolve()
    if args.action == "prepare":
        prepare(
            args.repository.resolve(),
            args.sandbox.resolve(),
            target,
            args.env_file.resolve(),
        )
    elif args.action == "preflight":
        preflight(target)
    else:
        raise SystemExit(asyncio.run(run(target, args.env_file.resolve())))
